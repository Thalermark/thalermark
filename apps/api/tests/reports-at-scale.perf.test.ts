// Reports at scale (TMC-188, item 3).
//
// Every report in routes/reports.ts is hand-written SQL over the general
// ledger, and until now none had been run against a book bigger than a test
// fixture. "It works" and "it works on 100,000 journal lines" are different
// claims, and only the second one matters to someone whose second year of
// trading is about to load a profit-and-loss.
//
// OPT-IN. Gated behind SCALE_TEST=1 so it never slows a PR — seeding is
// deliberately large and this is a tool for answering "did that change make
// reports slower?", not a per-commit gate. Committed rather than run once and
// thrown away, so the answer is reproducible:
//
//     SCALE_TEST=1 pnpm --filter @thalermark/api test reports-at-scale
//
// THE FIXTURE DOES NOT GO THROUGH THE API — that would take many minutes — but
// its LEDGER is generated by the real posting helpers (invoicePostingLines /
// expensePostingLines), the same pure functions the routes post through. This
// matters: a hand-written journal would measure a ledger shaped by this file's
// assumptions rather than by the code under test, and a posting-shape change
// would not show up here at all. scripts/seed-load-test.ts takes the same
// approach for the same reason — that script is the tool for seeding a real
// dev database by hand; this is the assertable, budgeted version.
//
// BUDGETS ARE DELIBERATELY GENEROUS. This is a regression detector, not a
// benchmark: the number that matters is "did this get 10x worse", not "is it
// 180ms or 240ms". A tight budget on shared CI hardware buys flakiness, and a
// flaky perf gate gets disabled within a month.

const SCALE = process.env.SCALE_TEST === '1';

